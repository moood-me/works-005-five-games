// the way as short pieces: [[lon, lat], [lon, lat], the share of the way at its middle, by] — each leg cut by its length into
// pieces of about a degree, its share running evenly along it from its stop's to the next one's
function pieces() {
  const out = [];
  WAY.forEach((leg, i) => {
    const to = i + 1 < WAY.length ? WAY[i + 1].at : 1, P = leg.pts;
    const lens = P.slice(1).map((p, j) => Math.hypot(p[0] - P[j][0], p[1] - P[j][1]));
    const all = lens.reduce((a, b) => a + b, 0);
    let gone = 0;
    lens.forEach((len, j) => {
      const n = Math.max(1, Math.round(len));
      for (let k = 1; k <= n; k++) {
        const u0 = (k - 1) / n, u1 = k / n, a = P[j], b = P[j + 1];
        const p0 = [a[0] + (b[0] - a[0]) * u0, a[1] + (b[1] - a[1]) * u0], p1 = [a[0] + (b[0] - a[0]) * u1, a[1] + (b[1] - a[1]) * u1];
        const share = u => leg.at + ((to - leg.at) * (gone + len * u)) / all;
        out.push([p0, p1, (share(u0) + share(u1)) / 2, leg.by]);
      }
      gone += len;
    });
  });
  return out;
}

